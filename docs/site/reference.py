"""Write the command reference from the operation registry: python docs/site/reference.py.

The registry is the single source of the CLI's commands and flags and of the MCP tools, so the
reference is generated from it; a test checks that docs/reference/cli.md is current."""

import sys
import types
import typing
from pathlib import Path
from typing import Any, get_args, get_origin

import msgspec

from beamtime.ops.registry import OPS, Op

OUT = Path(__file__).parents[1] / "reference" / "cli.md"
AREAS = {
    "beamtime.ops.reading": "Looking at runs",
    "beamtime.ops.record": "Proposals, notes and memory",
    "beamtime.ops.views": "Pages and views",
    "beamtime.ops.blocks": "Library blocks",
    "beamtime.ops.admin": "Setup and housekeeping",
}
INTRO = """# Command reference

Every command works the same from the command line and as an agent's tool (`note add` is the
tool `note_add`). Add `--json` to any command for its full answer, and `--root <dir>` to work on
another project. Commands marked *you* are for you alone: agents tell you to run them instead.

<!-- generated by docs/site/reference.py from the operation registry; don't edit by hand -->
"""


def reference() -> str:
    """Write the reference.

    :return: The Markdown."""
    parts = [INTRO]
    for module, title in AREAS.items():
        ops = [op for op in OPS if op.impl.split(":")[0] == module]
        if ops:
            parts.append(f"## {title}\n")
            parts += [command(op) for op in ops]
    return "\n".join(parts).rstrip() + "\n"


def command(op: Op) -> str:
    """Describe one command: its summary, its usage and its options.

    :param op: The operation.
    :return: The Markdown section."""
    fields = [f for f in msgspec.structs.fields(op.params) if f.encode_name != "cursor"]
    positional = [f for f in fields if f.name in op.positional]
    usage = " ".join(
        f"<{f.encode_name}>" if f.required else f"[{f.encode_name}]" for f in positional
    )
    who = " *(you)*" if op.user_only else ""
    lines = [
        f"### `beamtime {op.name}`{who}\n",
        op.summary,
        "",
        f"```sh\nbeamtime {op.name} {usage}".rstrip() + "\n```",
    ]
    options = [f for f in fields if f not in positional]
    if options:
        lines += ["", "| Option | Default | |", "|---|---|---|"]
        lines += [option(f) for f in options]
    return "\n".join(lines) + "\n"


def option(field: Any) -> str:
    """Describe one flag.

    :param field: The msgspec field.
    :return: A table row."""
    flag = f"`--{field.encode_name.replace('_', '-')}`"
    if field.required:
        default = "required"
    elif field.default is msgspec.NODEFAULT or field.default in (None, [], ()):
        default = ""
    else:
        default = f"`{field.default}`"
    return f"| {flag} | {default} | {describe(field.type)} |"


def describe(tp: Any) -> str:
    """Take a parameter's description, or name its choices.

    :param tp: The annotated type.
    :return: The text."""
    for meta in getattr(tp, "__metadata__", ()):
        if isinstance(meta, msgspec.Meta) and meta.description:
            return meta.description
    return ", ".join(str(c) for c in choices(tp))


def choices(tp: Any) -> list[Any]:
    """List the literal values a type allows.

    :param tp: A type annotation.
    :return: The values, e.g. ``["all", "a number"]``; empty for open types."""
    if tp in (int, float):
        return ["a number"]
    match get_origin(tp):
        case typing.Annotated:
            return choices(get_args(tp)[0])
        case typing.Literal:
            return list(get_args(tp))
        case typing.Union | types.UnionType:
            return [c for a in get_args(tp) for c in choices(a)]
        case _:
            return []


if __name__ == "__main__":
    OUT.write_text(reference())
    print(f"wrote {OUT}", file=sys.stderr)
