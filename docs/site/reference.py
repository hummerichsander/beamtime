"""Write the command reference from the operation registry: python docs/site/reference.py.

The registry is the single source of the CLI's commands and flags and of the MCP tools, so the
reference is generated from it; a test checks that docs/reference/cli.md is current."""

import sys
import types
import typing
from pathlib import Path
from typing import Any, get_args, get_origin

import msgspec

from beamtime.ops.registry import OPS, Op

OUT = Path(__file__).parents[1] / "reference" / "cli.md"
MCP_OUT = OUT.with_name("mcp.md")
AREAS = {
    "beamtime.ops.reading": "Looking at runs",
    "beamtime.ops.record": "Proposals, notes and memory",
    "beamtime.ops.copy": "Copying runs",
    "beamtime.ops.views": "Pages and views",
    "beamtime.ops.blocks": "Library blocks",
    "beamtime.ops.admin": "Setup and housekeeping",
    "beamtime.ops.procs": "Processes",
    "beamtime.ops.script": "Scripts",
}
INTRO = """# Command reference

Every command works the same from the command line and as an agent's tool (`note add` is the
tool `note_add`). Add `--json` to any command for its full answer, and `--root <dir>` to work on
another project. Commands marked *you* are for you alone: agents tell you to run them instead.
The same operations are the agent's [MCP tools](mcp.md).

<!-- generated by docs/site/reference.py from the operation registry; don't edit by hand -->
"""

MCP_EXAMPLE = """```python
a = bt.importance(from_="scaling/lr-sweep", target="metric.val/acc.max")
for row in a["rows"]:
    print(row["field"], row["eta_squared"])
```"""


def reference() -> str:
    """Write the reference.

    :return: The Markdown."""
    parts = [INTRO]
    for module, title in AREAS.items():
        ops = [op for op in OPS if op.impl.split(":")[0] == module]
        if ops:
            parts.append(f"## {title}\n")
            parts += [command(op) for op in ops]
    return "\n".join(parts).rstrip() + "\n"


def mcp_reference() -> str:
    """Write the MCP tool reference: the core tools, each family's tools, the user-only commands.

    :return: The Markdown."""
    from beamtime.mcp.server import CORE, FAMILIES  # the serve extra, needed only here
    from beamtime.ops.registry import BY_TOOL

    intro = f"""# MCP tools

Agents connect through `beamtime setup` (or `beamtime mcp install`) and call the same operations as
the [commands](cli.md), each as a tool named like its command path (`note add` is `note_add`). The
setting `mcp_tools: core` lists the {len(CORE)} core tools plus `tools_more`, which describes and
calls the tools of the families ({", ".join(FAMILIES)}); `all` lists all {len(BY_TOOL)}.

The `script` tool runs the Python an agent sends with `bt` preloaded: every operation is a function
whose answer is a plain dict, so the operations compute the statistics and Python joins and formats
what they return.

{MCP_EXAMPLE}

<!-- generated by docs/site/reference.py from the operation registry; don't edit by hand -->
"""
    parts = [intro, "## Core tools\n"]
    parts += [tool(BY_TOOL[name]) for name in CORE]
    for family, names in FAMILIES.items():
        parts.append(f"## Family: {family}\n")
        parts += [tool(BY_TOOL[name]) for name in names]
    parts.append("## Not for agents\n")
    parts.append("Agents never run these; they tell you the command instead.\n")
    parts += [f"- `beamtime {op.name}`: {op.summary}" for op in OPS if op.user_only]
    return "\n".join(parts).rstrip() + "\n"


def tool(op: Op) -> str:
    """Describe one MCP tool: its summary, its command and its parameters.

    :param op: The operation.
    :return: The Markdown section."""
    lines = [f"### `{op.tool}`\n", op.summary, "", f"CLI: `beamtime {op.name}`"]
    fields = [
        f
        for f in msgspec.structs.fields(op.params)
        if f.encode_name != "cursor" and not hidden(f.type)
    ]
    if fields:
        lines += ["", "| Parameter | Type | Default | |", "|---|---|---|---|"]
        for f in fields:
            lines.append(
                f"| `{f.encode_name}` | {typename(f.type)} | {default(f)} | {describe(f.type)} |"
            )
    return "\n".join(lines) + "\n"


def command(op: Op) -> str:
    """Describe one command: its summary, its usage and its options.

    :param op: The operation.
    :return: The Markdown section."""
    fields = [f for f in msgspec.structs.fields(op.params) if f.encode_name != "cursor"]
    positional = [f for f in fields if f.name in op.positional]
    usage = " ".join(
        f"<{f.encode_name}>" if f.required else f"[{f.encode_name}]" for f in positional
    )
    who = " *(you)*" if op.user_only else ""
    lines = [
        f"### `beamtime {op.name}`{who}\n",
        op.summary,
        "",
        f"```sh\nbeamtime {op.name} {usage}".rstrip() + "\n```",
    ]
    options = [f for f in fields if f not in positional and not hidden(f.type)]
    if options:
        lines += ["", "| Option | Default | |", "|---|---|---|"]
        lines += [option(f, f.name == op.stdin) for f in options]
    return "\n".join(lines) + "\n"


def option(field: Any, from_stdin: bool = False) -> str:
    """Describe one flag.

    :param field: The msgspec field.
    :param from_stdin: Whether the command reads it from stdin when the flag is absent.
    :return: A table row."""
    flag = f"`--{field.encode_name.replace('_', '-')}`"
    return f"| {flag} | {'stdin' if from_stdin else default(field)} | {describe(field.type)} |"


def default(field: Any) -> str:
    """Show a parameter's default.

    :param field: The msgspec field.
    :return: ``required``, the value in code font, or nothing for an unset parameter."""
    if field.required:
        return "required"
    if field.default is msgspec.NODEFAULT or field.default in (None, [], ()):
        return ""
    return f"`{field.default}`"


def hidden(tp: Any) -> bool:
    """Tell whether a parameter is a hidden alias that the reference leaves out.

    :param tp: The annotated type.
    :return: Whether its ``Meta`` says ``hidden``."""
    return any(
        isinstance(meta, msgspec.Meta) and (meta.extra or {}).get("hidden")
        for meta in getattr(tp, "__metadata__", ())
    )


def describe(tp: Any) -> str:
    """Take a parameter's description, or name its choices.

    :param tp: The annotated type.
    :return: The text."""
    for meta in getattr(tp, "__metadata__", ()):
        if isinstance(meta, msgspec.Meta) and meta.description:
            return meta.description
    return ", ".join(str(c) for c in choices(tp))


def choices(tp: Any) -> list[Any]:
    """List the literal values a type allows.

    :param tp: A type annotation.
    :return: The values, e.g. ``["all", "a number"]``; empty for open types."""
    if tp in (int, float):
        return ["a number"]
    match get_origin(tp):
        case typing.Annotated:
            return choices(get_args(tp)[0])
        case typing.Literal:
            return list(get_args(tp))
        case typing.Union | types.UnionType:
            return [c for a in get_args(tp) for c in choices(a)]
        case _:
            return []


def typename(tp: Any) -> str:
    """Name a parameter's type as JSON: ``string``, ``integer``, ``list of string``, ...

    :param tp: The annotated type.
    :return: The name; ``null`` alternatives are left to the default column."""
    match get_origin(tp):
        case typing.Annotated:
            return typename(get_args(tp)[0])
        case typing.Literal:
            return "\\|".join(str(c) for c in get_args(tp))
        case typing.Union | types.UnionType:
            return " or ".join(typename(a) for a in get_args(tp) if a is not type(None))
        case None:
            pass
        case origin if origin in (list, tuple, set):
            return f"list of {typename(get_args(tp)[0])}"
        case _:
            return "object"
    return {str: "string", bool: "boolean", int: "integer", float: "number"}.get(tp, "object")


if __name__ == "__main__":
    OUT.write_text(reference())
    MCP_OUT.write_text(mcp_reference())
    print(f"wrote {OUT} and {MCP_OUT}", file=sys.stderr)
